-- DDL para Sistema de Avaliação de Maturidade Organizacional (NIST CSF)
-- Banco de Dados: Oracle Database

-- 1. Estrutura de RBAC (Controle de Acesso)
CREATE TABLE PERFIS (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NOME VARCHAR2(50) NOT NULL UNIQUE
);

CREATE TABLE USUARIOS (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    EMAIL VARCHAR2(255) NOT NULL UNIQUE,
    NOME VARCHAR2(255) NOT NULL,
    STATUS VARCHAR2(20) DEFAULT 'ATIVO' CHECK (STATUS IN ('ATIVO', 'INATIVO')),
    PERFIL_ID NUMBER NOT NULL,
    CONSTRAINT FK_USUARIO_PERFIL FOREIGN KEY (PERFIL_ID) REFERENCES PERFIS(ID)
);

-- 2. Taxonomia NIST CSF 2.0
CREATE TABLE NIST_FUNCOES (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CODIGO VARCHAR2(10) NOT NULL UNIQUE,
    NOME VARCHAR2(100) NOT NULL,
    COR VARCHAR2(20)
);

CREATE TABLE NIST_CATEGORIAS (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    FUNCAO_ID NUMBER NOT NULL,
    CODIGO VARCHAR2(20) NOT NULL UNIQUE,
    NOME VARCHAR2(255) NOT NULL,
    DESCRICAO VARCHAR2(1000),
    CONSTRAINT FK_CATEGORIA_FUNCAO FOREIGN KEY (FUNCAO_ID) REFERENCES NIST_FUNCOES(ID)
);

CREATE TABLE NIST_SUBCATEGORIAS (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CATEGORIA_ID NUMBER NOT NULL,
    CODIGO VARCHAR2(20) NOT NULL UNIQUE,
    DESCRICAO CLOB NOT NULL,
    STATUS VARCHAR2(20) DEFAULT 'ATIVO' CHECK (STATUS IN ('ATIVO', 'RETIRADO')),
    CONSTRAINT FK_SUBCATEGORIA_CATEGORIA FOREIGN KEY (CATEGORIA_ID) REFERENCES NIST_CATEGORIAS(ID)
);

CREATE TABLE NIST_EXEMPLOS_IMPLEMENTACAO (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    SUBCATEGORIA_ID NUMBER NOT NULL,
    EXEMPLO CLOB NOT NULL,
    CONSTRAINT FK_EXEMPLO_SUBCATEGORIA FOREIGN KEY (SUBCATEGORIA_ID) REFERENCES NIST_SUBCATEGORIAS(ID)
);

-- 3. Cenários e Avaliações
CREATE TABLE CENARIOS (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NOME VARCHAR2(255) NOT NULL,
    TIPO VARCHAR2(10) NOT NULL CHECK (TIPO IN ('ATUAL', 'ALVO')),
    STATUS VARCHAR2(20) NOT NULL CHECK (STATUS IN ('EM_ELABORACAO', 'VIGENTE', 'ARQUIVADO', 'PENDENTE_APROVACAO')),
    DATA_CRIACAO TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    DATA_EFETIVACAO TIMESTAMP,
    CRIADO_POR NUMBER NOT NULL,
    CONSTRAINT FK_CENARIO_USUARIO FOREIGN KEY (CRIADO_POR) REFERENCES USUARIOS(ID)
);

CREATE TABLE AVALIACOES_SUBCATEGORIA (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CENARIO_ID NUMBER NOT NULL,
    SUBCATEGORIA_ID NUMBER NOT NULL,
    STATUS_MATURIDADE VARCHAR2(50) CHECK (STATUS_MATURIDADE IN ('ATENDIDO', 'RAZOAVELMENTE_ATENDIDO', 'PARCIALMENTE_ATENDIDO', 'DEFICITARIAMENTE_ATENDIDO', 'NAO_ATENDIDO')),
    PRIORIDADE VARCHAR2(10) CHECK (PRIORIDADE IN ('ALTA', 'MEDIA', 'BAIXA')),
    NIVEL_IMPLEMENTACAO NUMBER CHECK (NIVEL_IMPLEMENTACAO IN (1, 2, 3, 4)),
    JUSTIFICATIVA CLOB,
    POLITICAS_ALVO CLOB,
    PRATICAS_ALVO CLOB,
    RESPONSABILIDADES_ALVO CLOB,
    CONSTRAINT FK_AVALIACAO_CENARIO FOREIGN KEY (CENARIO_ID) REFERENCES CENARIOS(ID),
    CONSTRAINT FK_AVALIACAO_SUBCAT FOREIGN KEY (SUBCATEGORIA_ID) REFERENCES NIST_SUBCATEGORIAS(ID),
    CONSTRAINT UK_AVALIACAO_CEN_SUB UNIQUE (CENARIO_ID, SUBCATEGORIA_ID)
);

-- 4. Planos de Ação e Evidências
CREATE TABLE PLANOS_ACAO (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    AVALIACAO_ID NUMBER NOT NULL,
    DESCRICAO CLOB NOT NULL,
    PRAZO DATE,
    RESPONSAVEL VARCHAR2(255),
    STATUS VARCHAR2(20) DEFAULT 'PENDENTE' CHECK (STATUS IN ('PENDENTE', 'EM_ANDAMENTO', 'CONCLUIDO', 'CANCELADO')),
    CONSTRAINT FK_PLANO_AVALIACAO FOREIGN KEY (AVALIACAO_ID) REFERENCES AVALIACOES_SUBCATEGORIA(ID)
);

CREATE TABLE EVIDENCIAS (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    AVALIACAO_ID NUMBER NOT NULL,
    TIPO VARCHAR2(50) NOT NULL,
    CAMINHO_URL VARCHAR2(1000) NOT NULL,
    DATA_INCLUSAO TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT FK_EVIDENCIA_AVALIACAO FOREIGN KEY (AVALIACAO_ID) REFERENCES AVALIACOES_SUBCATEGORIA(ID)
);

-- 5. Propostas de Alteração (Workflow)
CREATE TABLE PROPOSTAS_ALTERACAO (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CENARIO_ID NUMBER NOT NULL,
    SUBCATEGORIA_ID NUMBER NOT NULL,
    REQUERENTE_ID NUMBER NOT NULL,
    JUSTIFICATIVA CLOB NOT NULL,
    VALOR_ANTERIOR CLOB,
    NOVO_VALOR CLOB,
    STATUS VARCHAR2(20) DEFAULT 'PENDENTE' CHECK (STATUS IN ('PENDENTE', 'APROVADA', 'REJEITADA')),
    APROVADOR_ID NUMBER,
    DATA_SOLICITACAO TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    DATA_APROVACAO TIMESTAMP,
    CONSTRAINT FK_PROPOSTA_CENARIO FOREIGN KEY (CENARIO_ID) REFERENCES CENARIOS(ID),
    CONSTRAINT FK_PROPOSTA_SUBCAT FOREIGN KEY (SUBCATEGORIA_ID) REFERENCES NIST_SUBCATEGORIAS(ID),
    CONSTRAINT FK_PROPOSTA_REQUERENTE FOREIGN KEY (REQUERENTE_ID) REFERENCES USUARIOS(ID),
    CONSTRAINT FK_PROPOSTA_APROVADOR FOREIGN KEY (APROVADOR_ID) REFERENCES USUARIOS(ID)
);

-- 6. Trilha de Auditoria
CREATE TABLE AUDITORIA_LOG (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USUARIO_ID NUMBER,
    DATA_HORA_UTC TIMESTAMP DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP),
    ACAO VARCHAR2(50) NOT NULL,
    MODULO VARCHAR2(100) NOT NULL,
    ENTIDADE_AFETADA VARCHAR2(100),
    REGISTRO_ID NUMBER,
    VALORES_ANTERIORES CLOB,
    NOVOS_VALORES CLOB,
    IP_ORIGEM VARCHAR2(50)
);

